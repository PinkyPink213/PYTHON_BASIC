# ลองพิมพ์ตัวแปรอย่างละหนึ่งตัว:
# - ข้อความหนึ่งค่า ใช้เครื่องหมายคำพูด -> str
# - จำนวนเต็มหนึ่งค่า ไม่มีจุดทศนิยม -> int
# - จำนวนทศนิยมหนึ่งค่า มีจุดทศนิยม -> float
# - ค่าความจริงหนึ่งค่า ใช้ True หรือ False -> bool

# เฉลยตัวอย่าง
name = "Mali"
age = 10
height = 135.5
is_student = True

# ก่อน Run ลองทายว่า type() แต่ละบรรทัดจะแสดงอะไร
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))


