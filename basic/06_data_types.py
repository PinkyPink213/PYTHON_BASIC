print("--- Four basic data types ---")
name = "Mali"       # str: ข้อความ
age = 10            # int: จำนวนเต็ม
height = 135.5      # float: จำนวนทศนิยม
is_student = True   # bool: True หรือ False

print(type(name))
print(type(age))
print(type(height))
print(type(is_student))


print("\n--- Values that look different ---")
number = 10
