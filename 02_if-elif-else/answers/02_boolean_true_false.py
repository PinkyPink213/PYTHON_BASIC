"""เฉลยบทที่ 2: Boolean — True และ False"""

print("--- Example 1: Boolean values ---")
is_sunny = True
is_raining = False
print(is_sunny)
print(is_raining)

print("\n--- Example 2: A comparison makes a Boolean ---")
age = 10
is_old_enough = age >= 8
print(is_old_enough)

print("\n--- Example 3: Boolean in an if ---")
homework_done = True
if homework_done:
    print("The homework is finished!")
else:
    print("Finish the homework first.")

