"""เฉลยบทที่ 5: Variable Naming Rules"""

# ==================================================
# สิ่งที่บทนี้สอน
# ==================================================
# ชื่อตัวแปรที่ถูกต้อง:
# - ใช้ตัวอักษร ตัวเลข และเครื่องหมาย _ ได้
# - ห้ามขึ้นต้นด้วยตัวเลข
# - ห้ามมีช่องว่าง
# - ห้ามใช้เครื่องหมาย -
# - ห้ามใช้คำสงวนของ Python เช่น if, for และ True
# - ควรตั้งชื่อให้อ่านแล้วเข้าใจว่าตัวแปรเก็บอะไร
#
# รูปแบบที่เราใช้เรียกว่า snake_case
# คือใช้ตัวพิมพ์เล็กและใช้ _ แทนช่องว่าง
# ตัวอย่าง: player_name, favorite_color, number_of_hearts


# ==================================================
# เฉลย Your turn 1: แก้ชื่อที่ผิด
# ==================================================

# ชื่อเดิม: student name
# ปัญหา: ชื่อตัวแปรห้ามมีช่องว่าง
# วิธีแก้: เปลี่ยนช่องว่างเป็น _
student_name = "Mali"

# ชื่อเดิม: 1st_score
# ปัญหา: ชื่อตัวแปรห้ามขึ้นต้นด้วยตัวเลข
# วิธีแก้: เขียนคำว่า first แทนเลข 1
first_score = 20

# ชื่อเดิม: favorite-color
# ปัญหา: เครื่องหมาย - หมายถึงการลบ จึงใช้ในชื่อตัวแปรไม่ได้
# วิธีแก้: เปลี่ยน - เป็น _
favorite_color = "green"


# ==================================================
# เฉลย Your turn 2: ตั้งชื่อให้สื่อความหมาย
# ==================================================

# game_name บอกชัดเจนว่าตัวแปรเก็บชื่อของเกม
game_name = "Dragon Cave"

# number_of_hearts บอกชัดเจนว่าเก็บจำนวนหัวใจ
# ตัวเลข 3 อยู่ด้านหลังเครื่องหมาย = จึงใช้เก็บเป็นค่าได้ตามปกติ
number_of_hearts = 3


# แสดงค่าที่เก็บอยู่ในตัวแปรเพื่อตรวจสอบผลลัพธ์
print(student_name, first_score, favorite_color)
print(game_name, number_of_hearts)


# ลองสังเกตชื่อเหล่านี้:
# score และ Score เป็นคนละตัวแปร เพราะ Python แยกตัวพิมพ์เล็กและใหญ่
# การใช้ตัวพิมพ์เล็กแบบ snake_case ช่วยลดความสับสน
